
import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
import nodemailer from 'nodemailer';
import rateLimit from 'express-rate-limit';

dotenv.config();

const app = express();
const PORT = process.env.PORT || 5000;

app.use(express.json({ limit: '1mb' }));

// Allow only configured frontend origins.
const allowedOrigins = [
  ...(process.env.FRONTEND_URL || 'http://localhost:5173')
    .split(',')
    .map(url => url.trim().replace(/\/$/, '')),
  'http://localhost:5173',
  'http://127.0.0.1:5173',
].filter(Boolean);

app.use(cors({
  origin(origin, callback) {
    if (
      !origin ||
      allowedOrigins.includes(origin.replace(/\/$/, '')) ||
      /^https:\/\/[a-z0-9-]+\.vercel\.app$/.test(origin)
    ) {
      return callback(null, true);
    }

    return callback(new Error('Origin not allowed by CORS'));
  },
}));

const contactLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  max: 10,
  standardHeaders: true,
  legacyHeaders: false,
  message: {
    success: false,
    error: 'Too many requests. Please try again in 15 minutes.',
  },
});

function escapeHtml(value = '') {
  return String(value).replace(/[&<>"']/g, char => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  })[char]);
}

app.get('/health', (req, res) => {
  res.status(200).json({
    status: 'ok',
    service: 'solzen-backend',
    timestamp: new Date().toISOString(),
  });
});

app.get('/', (req, res) => {
  res.send('SOLZEN Email API is running. Contact endpoint: /api/contact');
});

app.post('/api/contact', contactLimiter, async (req, res) => {
  try {
    const { name, email, subject, message } = req.body || {};

    if (typeof name !== 'string' || !name.trim()) {
      return res.status(400).json({
        success: false,
        error: 'Full name is required.',
      });
    }

    if (
      typeof email !== 'string' ||
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim())
    ) {
      return res.status(400).json({
        success: false,
        error: 'A valid email address is required.',
      });
    }

    if (typeof subject !== 'string' || !subject.trim()) {
      return res.status(400).json({
        success: false,
        error: 'Subject is required.',
      });
    }

    if (typeof message !== 'string' || !message.trim()) {
      return res.status(400).json({
        success: false,
        error: 'Message content is required.',
      });
    }

    const trimmedName = name.trim();
    const trimmedEmail = email.trim();
    const trimmedSubject = subject.trim();
    const trimmedMessage = message.trim();

    const gmailUser = process.env.GMAIL_USER;
    const gmailPass = process.env.GMAIL_APP_PASSWORD;
    const receiver = process.env.CONTACT_RECEIVER || gmailUser;

    if (!gmailUser || !gmailPass || !receiver) {
      console.error('Missing mail configuration in backend/.env');

      return res.status(500).json({
        success: false,
        error: 'Email service is not configured correctly.',
      });
    }

    const transporter = nodemailer.createTransport({
      service: 'gmail',
      auth: {
        user: gmailUser,
        pass: gmailPass.replace(/\s+/g, ''),
      },
    });

    const safeName = escapeHtml(trimmedName);
    const safeEmail = escapeHtml(trimmedEmail);
    const safeSubject = escapeHtml(trimmedSubject);
    const safeMessage = escapeHtml(trimmedMessage);

    const mailOptions = {
      from: `"SOLZEN Website" <${gmailUser}>`,
      to: receiver,
      replyTo: trimmedEmail,
      subject: `New Contact Inquiry — ${trimmedSubject}`,

      text: `
Hello SOLZEN Team,

A new inquiry was submitted through the SOLZEN website.

CONTACT DETAILS
Name: ${trimmedName}
Email: ${trimmedEmail}
Subject: ${trimmedSubject}

MESSAGE
${trimmedMessage}

Reply directly to this email to contact the visitor.

---
Automatically generated by the SOLZEN website contact form.
      `.trim(),

      html: `
        <div style="font-family:Arial,sans-serif;max-width:640px;margin:auto;color:#222;line-height:1.6">
          <div style="background:#172554;color:#fff;padding:24px;border-radius:10px 10px 0 0">
            <h2 style="margin:0">SOLZEN</h2>
            <p style="margin:6px 0 0">New Contact Inquiry</p>
          </div>

          <div style="padding:24px;border:1px solid #e5e7eb">
            <p>Hello SOLZEN Team,</p>
            <p>A new inquiry was submitted through your website contact form.</p>

            <h3>Contact Details</h3>
            <p>
              <strong>Name:</strong> ${safeName}<br>
              <strong>Email:</strong> ${safeEmail}<br>
              <strong>Subject:</strong> ${safeSubject}
            </p>

            <h3>Message</h3>
            <div style="background:#f8fafc;padding:16px;border-left:4px solid #2563eb;white-space:pre-wrap;overflow-wrap:anywhere">${safeMessage.replace(/\n/g, '<br>')}</div>

            <p style="margin-top:24px">
              Reply directly to this email to respond to the visitor.
            </p>
          </div>

          <p style="font-size:12px;color:#6b7280;text-align:center">
            Automatically generated by the SOLZEN website contact form.
          </p>
        </div>
      `,
    };

    const info = await transporter.sendMail(mailOptions);

    console.log('Email accepted by SMTP server:', info.messageId);

    return res.status(200).json({
      success: true,
      message: 'Your message has been sent successfully.',
    });
  } catch (error) {
    console.error('Contact email error:', error.message);

    return res.status(500).json({
      success: false,
      error: 'Unable to send your message right now. Please try again or email our team directly.',
    });
  }
});

app.listen(PORT, () => {
  console.log(`[SOLZEN Backend] Running on port ${PORT}`);
});
